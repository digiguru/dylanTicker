export function normalizeText(text) {
  return String(text ?? '').toUpperCase().replace(/\s+/g, ' ');
}

export function columnsForText(text, { gap = 1 } = {}) {
  const normalized = normalizeText(text);
  const columns = [];

  for (const character of normalized) {
    const glyph = GLYPHS[character] ?? GLYPHS['?'];
    columns.push(...glyph.map((rows) => [...rows]));
    for (let i = 0; i < gap; i += 1) columns.push([]);
  }

  return columns.length > 0 ? columns : [[]];
}

export function chunkColumns(columns, maxColumns = 2048) {
  if (!Number.isInteger(maxColumns) || maxColumns < 1) {
    throw new RangeError('maxColumns must be a positive integer');
  }

  const chunks = [];
  for (let index = 0; index < columns.length; index += maxColumns) {
    chunks.push(columns.slice(index, index + maxColumns));
  }
  return chunks.length > 0 ? chunks : [[[]]];
}
